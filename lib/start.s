/* start.s — точка входу USER-програми (аналог boot.s, але для Ring3
 * процесу, не для всього ядра). МАЄ бути ПЕРШИМИ байтами в лінкованому
 * бінарнику (build.sh лінкує ЦЕЙ файл ПЕРШИМ) - process_create_from_bytes
 * (process.c) просто ставить eip=початок файлу, без жодного знання про
 * символи/ELF-заголовки.
 *
 * Ядро (process.c, build_args) кладе на вершину стека [esp]=argc,
 * [esp+4]=argv - рівно так, як cdecl чекає аргументи main ПІСЛЯ адреси
 * повернення, тож `call main` віддає їх як main(argc, argv). Програми зі
 * старим main(void) просто їх не читають.
 */
.global _start
_start:
    call main

    /* Повернення з main - вихід із кодом, який main повернула (eax). Без
     * цього процес "провалився" б у сміття за кінцем свого коду. */
    mov %eax, %ebx
    mov $0, %eax
    int $0x80
1:  jmp 1b
